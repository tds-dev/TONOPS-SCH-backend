"""Order系のモデルから、DB作成と全テーブル作成のSQL Server用SQLを出力する。

    python -m scripts.export_ddl

DBA レビューや SSMS での手動作成に使う。DB への接続は不要。
"""
import argparse
from pathlib import Path

from sqlalchemy.dialects import mssql
from sqlalchemy.schema import CreateIndex, CreateTable

from app import models  # noqa: F401
from app.core.db import Base

OUT = Path(__file__).resolve().parent.parent / "db" / "schema_sqlserver.sql"
# DB作成SQLとテーブル作成SQLは、実行順が分かるよう別ファイルへ出力する。
DATABASE_OUT = OUT.with_name("create_database_sqlserver.sql")


def quote_identifier(name: str) -> str:
    """SQL Serverのテーブル名・列名・DB名を角括弧で囲む。"""
    return "[" + name.replace("]", "]]") + "]"


def render_database_sql(database_name: str = "TONOPS-SCH") -> str:
    """指定DBが存在しない場合だけ作成するSQLを生成する。実行は行わない。"""
    escaped_name = database_name.replace("'", "''")
    return (
        "-- DBを作成するSQL。自動実行は行わない。\nUSE [master];\nGO\n"
        f"IF DB_ID(N'{escaped_name}') IS NULL\nBEGIN\n"
        f"    CREATE DATABASE {quote_identifier(database_name)};\nEND;\nGO\n"
    )


def render_schema_sql(database_name: str = "TONOPS-SCH") -> str:
    """モデルからOrder系のテーブル・インデックス・外部キーを生成する。"""
    dialect = mssql.dialect()
    parts = [
        "-- Generated by scripts/export_ddl.py — do not edit by hand.\n"
        "-- 新規DB向けの作成SQL。既存DBの名称変更用SQLではない。\n",
        f"USE {quote_identifier(database_name)};\nGO\n",
    ]
    # 参照先のテーブルを先に作成し、同じ出力順で再生成できるようにする。
    for table in Base.metadata.sorted_tables:
        parts.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\nGO\n")
        for index in sorted(table.indexes, key=lambda item: item.name):
            parts.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";\nGO\n")
    # 拠点とカレンダー等の相互参照は、全テーブルを作った後に追加する。
    # コンパイラーを直接使い、共有モデルの外部キー定義は変更しない。
    compiler = dialect.ddl_compiler(dialect, None)
    for table in Base.metadata.sorted_tables:
        for constraint in sorted(table.foreign_key_constraints, key=lambda item: item.name):
            if constraint.use_alter:
                table_name = compiler.preparer.format_table(table)
                definition = compiler.process(constraint)
                parts.append(f"ALTER TABLE {table_name} ADD {definition};\nGO\n")
    return "\n".join(parts)

if __name__ == "__main__":
    # 出力先DB名だけを受け取り、DB接続やSQL実行は行わない。
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database-name", default="TONOPS-SCH")
    args = parser.parse_args()
    OUT.parent.mkdir(exist_ok=True)
    DATABASE_OUT.write_text(render_database_sql(args.database_name), encoding="utf-8")
    OUT.write_text(render_schema_sql(args.database_name), encoding="utf-8")
    print(f"Wrote {DATABASE_OUT}")
    print(f"Wrote {OUT}")
