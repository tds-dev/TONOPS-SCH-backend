"""Write SQL Server DDL for all tables to db/schema_sqlserver.sql.

    python -m scripts.export_ddl

Useful for DBA review or creating the schema by hand in SSMS.
No database connection is needed.
"""
from pathlib import Path

from sqlalchemy.dialects import mssql
from sqlalchemy.schema import CreateIndex, CreateTable

from app import models  # noqa: F401
from app.core.db import Base

OUT = Path(__file__).resolve().parent.parent / "db" / "schema_sqlserver.sql"

if __name__ == "__main__":
    dialect = mssql.dialect()
    parts = ["-- Generated by scripts/export_ddl.py — do not edit by hand.\n"]
    for table in Base.metadata.sorted_tables:
        parts.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";\nGO\n")
        for index in table.indexes:
            parts.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";\nGO\n")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"Wrote {OUT}")
