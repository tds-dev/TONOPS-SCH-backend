"""既存のデモ登録処理をメモリDBで実行し、Order系のSQL Server用INSERT文だけを出力する。"""
import argparse
from datetime import date, datetime, time
from decimal import Decimal
import json
from pathlib import Path
from zoneinfo import ZoneInfo

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.db import Base, make_engine
from app.services.demo_seed import seed_demo
from scripts.export_ddl import quote_identifier

# 生成先はSQLファイルだけとし、実DBへの挿入処理とは分離する。
OUT = Path(__file__).resolve().parent.parent / "db" / "seed_demo_sqlserver.sql"


def sql_value(value) -> str:
    """日本語・JSON・日付等をSQL Serverで扱えるSQLリテラルへ変換する。"""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (dict, list)):
        value = json.dumps(value, ensure_ascii=False)
    if isinstance(value, datetime):
        return "'" + value.isoformat(timespec="microseconds") + "'"
    if isinstance(value, (date, time)):
        return "'" + value.isoformat() + "'"
    if isinstance(value, str):
        return "N'" + value.replace("'", "''") + "'"
    if isinstance(value, (int, float, Decimal)):
        return str(value)
    raise TypeError(f"SQL出力に対応していない値: {type(value).__name__}")


def demo_rows(now: datetime | None = None) -> dict[str, list[dict]]:
    """実DBへ接続せず、既存処理で生成したデモデータをメモリ上で取得する。"""
    engine = make_engine("sqlite://")
    try:
        Base.metadata.create_all(engine)
        with Session(engine) as db:
            seed_demo(db, now=now)
            # 外部キー順で出力できるよう、テーブルと主キーの順序を固定する。
            return {
                table.name: [dict(row) for row in db.execute(select(table).order_by(*table.primary_key.columns)).mappings()]
                for table in Base.metadata.sorted_tables
            }
    finally:
        engine.dispose()


def render_seed_sql(rows_by_table: dict[str, list[dict]], database_name: str = "TONOPS-SCH") -> str:
    """IDと参照関係を維持し、新規DB向けのデモデータ挿入SQLを生成する。"""
    parts = [
        "-- Generated by scripts/export_seed_sql.py — do not edit by hand.",
        "-- 新規作成した空のDB向け。既存データの変換は行わない。",
        f"USE {quote_identifier(database_name)};\nGO",
        "SET XACT_ABORT ON;",
        "IF EXISTS (SELECT 1 FROM [M_Organizations])\nBEGIN\n"
        "    THROW 50001, N'初期データは空のDBに対して実行してください。', 1;\nEND;",
        "DECLARE @IdentityTable sysname = NULL;\nDECLARE @CleanupSql nvarchar(512);\nBEGIN TRY\nBEGIN TRANSACTION;",
    ]
    inserted = set()
    deferred_updates = []
    for table in Base.metadata.sorted_tables:
        rows = rows_by_table[table.name]
        if not rows:
            continue
        table_name = quote_identifier(table.name)
        identity = table.autoincrement_column is not None
        parts.append(f"\n-- {table.name}: {len(rows)}件")
        if identity:
            parts.extend([f"SET @IdentityTable = N'{table.name}';", f"SET IDENTITY_INSERT {table_name} ON;"])
        for original in rows:
            row = dict(original)
            # まだ挿入していない参照先は、一旦NULLにして全件挿入後に設定する。
            for column in table.columns:
                if row[column.name] is None:
                    continue
                if any(fk.column.table.name not in inserted and fk.column.table is not table for fk in column.foreign_keys):
                    if not column.nullable:
                        raise ValueError(f"先に挿入すべき参照先がない: {table.name}.{column.name}")
                    where = " AND ".join(f"{quote_identifier(pk.name)} = {sql_value(row[pk.name])}" for pk in table.primary_key.columns)
                    deferred_updates.append(f"UPDATE {table_name} SET {quote_identifier(column.name)} = {sql_value(row[column.name])} WHERE {where};")
                    row[column.name] = None
            columns = ", ".join(quote_identifier(column.name) for column in table.columns)
            values = ", ".join(sql_value(row[column.name]) for column in table.columns)
            parts.append(f"INSERT INTO {table_name} ({columns}) VALUES ({values});")
        if identity:
            parts.extend([f"SET IDENTITY_INSERT {table_name} OFF;", "SET @IdentityTable = NULL;"])
        inserted.add(table.name)
    parts.extend([
        "\n-- 拠点の標準カレンダー等、後から参照先ができる項目を設定する。",
        *deferred_updates,
        "COMMIT TRANSACTION;\nEND TRY\nBEGIN CATCH",
        "IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;",
        "IF @IdentityTable IS NOT NULL\nBEGIN\n"
        "    SET @CleanupSql = N'SET IDENTITY_INSERT ' + QUOTENAME(@IdentityTable) + N' OFF;';\n"
        "    EXEC sys.sp_executesql @CleanupSql;\nEND;",
        "THROW;\nEND CATCH;\nGO\n",
    ])
    return "\n".join(parts)


if __name__ == "__main__":
    # 基準日は任意指定とし、未指定の場合はデモ登録処理の現在日時を使う。
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database-name", default="TONOPS-SCH")
    parser.add_argument("--base-date", type=date.fromisoformat)
    args = parser.parse_args()
    now = datetime.combine(args.base_date, time(10), ZoneInfo("Asia/Tokyo")) if args.base_date else None
    rows = demo_rows(now)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(render_seed_sql(rows, args.database_name), encoding="utf-8")
    print(f"Wrote {OUT} (orders={len(rows['T_Orders'])}, tasks={len(rows['T_Tasks'])})")
